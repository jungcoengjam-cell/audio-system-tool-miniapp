const fs = require('fs')
const path = require('path')
const wiringModel = require('../pages/audio-wiring/wiring-model')
const renderer = require('../pages/audio-wiring/wiring-renderer')

const outputDirectory = path.join(__dirname, '../pages/audio-wiring')
const modelSignatures = []
const endpointSignatures = []
const modelIndexes = new Map()
const endpointIndexes = new Map()
const entries = {}

function intern(value, values, indexes) {
  if (!indexes.has(value)) {
    indexes.set(value, values.length)
    values.push(value)
  }
  return indexes.get(value)
}

for (const output of wiringModel.OUTPUT_OPTIONS) {
  for (const input of wiringModel.INPUT_OPTIONS) {
    const model = wiringModel.getWiringModel(output.id, input.id)
    if (!model.supported) continue
    const key = JSON.stringify([model.output.id, model.input.id])
    if (entries[key]) throw new Error(`Duplicate solder route table model: ${key}`)
    const generated = renderer.createCanonicalSolderRouteTableEntry(model)
    entries[key] = {
      model: intern(generated.model, modelSignatures, modelIndexes),
      output: intern(generated.outputGeometry, endpointSignatures, endpointIndexes),
      input: intern(generated.inputGeometry, endpointSignatures, endpointIndexes),
      geometryHeader: generated.geometryHeader,
      routes: generated.routes,
    }
  }
}

if (Object.keys(entries).length !== 63) {
  throw new Error(`Expected 63 supported default models, generated ${Object.keys(entries).length}`)
}

const sourceTable = {
  modelSignatures: modelSignatures.map((value) => JSON.parse(value)),
  endpointSignatures: endpointSignatures.map((value) => JSON.parse(value)),
  entries,
}
const nodes = []
const nodeByJson = new Map()
function encode(value) {
  const key = JSON.stringify(value)
  if (key === undefined) throw new Error('Unsupported value in solder route table')
  if (nodeByJson.has(key)) return nodeByJson.get(key)
  let node
  if (Array.isArray(value)) node = value.map(encode)
  else if (value && typeof value === 'object') {
    node = [-1]
    Object.keys(value).forEach((property) => node.push(encode(property), encode(value[property])))
  } else node = value
  const id = nodes.length
  nodes.push(node)
  nodeByJson.set(key, id)
  return id
}

const rootNodeId = encode(sourceTable)
const packedJson = JSON.stringify([rootNodeId, nodes])
const source = `// Generated by tests/generate-audio-wiring-solder-route-table.cjs. Do not edit by hand.\nconst [rootNodeId, nodes] = ${packedJson}\nconst memo = new Array(nodes.length)\nfunction decode(id) {\n  if (Object.prototype.hasOwnProperty.call(memo, id)) return memo[id]\n  const node = nodes[id]\n  if (!Array.isArray(node)) { memo[id] = node; return node }\n  if (node[0] === -1) {\n    const value = {}\n    memo[id] = value\n    for (let index = 1; index < node.length; index += 2) value[decode(node[index])] = decode(node[index + 1])\n    return value\n  }\n  const value = []\n  memo[id] = value\n  for (const child of node) value.push(decode(child))\n  return value\n}\nconst table = decode(rootNodeId)\ntable.modelSignatures = table.modelSignatures.map((value) => JSON.stringify(value))\ntable.endpointSignatures = table.endpointSignatures.map((value) => JSON.stringify(value))\nmodule.exports = table\n`
const sourceBytes = Buffer.byteLength(source)
if (sourceBytes >= 160 * 1024) throw new Error(`Packed solder route table exceeds the 160 KiB source-file limit: ${sourceBytes}B`)
fs.writeFileSync(path.join(outputDirectory, 'solder-route-table-data.js'), source, 'utf8')
process.stdout.write(`Generated ${Object.keys(entries).length} canonical solder route sets (${nodes.length} deduplicated nodes, ${sourceBytes}B).\n`)
